#!/usr/bin/env python3
"""Builds the custom-cup patch (tools/cup_patch.s) for F-Zero GX (GFZE01).

  build_cup_patch.py header            regenerate src/cup_patch_blob.hpp
  build_cup_patch.py dol IN OUT [CUPS] patch a main.dol for testing; CUPS like
                                       "Editor Cup:7,13,21,25,27:0xa131"
                                       (several separated by ';')

Needs llvm-mc (only to build; the editor uses the generated header).
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ppcasm import Assembler  # noqa: E402

BASE = 0x801B7940          # old arena start (stack end 0x801b7930, aligned)
SIZE = 0x1000              # reserved; the arena now starts at BASE + SIZE

# Runtime addresses observed with GLINUX (module 1 at 0x801ba700, module 10 at
# 0x805960a0); only offsets within a section are used.
M1 = {1: 0x801BA7DC, 4: 0x80319E10, 5: 0x80327D00, 6: 0x80374740}
SEL = {1: 0x8059617C, 4: 0x805BCB28, 5: 0x805BE950}
SYMBOLS = {
    'BASE': BASE,
    'M1_SETUP': 0x803FFAE0 - M1[6],
    'M1_TABLE1': 0x80322040 - M1[4],
    'M1_TABLE2': 0x803220C4 - M1[4],
    'M1_TABLE3': 0x80322148 - M1[4],
    'M1_FINDCUP': 0x802E975C - M1[1],
    'SEL_STEP_REJECT': 0x805A0CE0 - SEL[1],
    'SEL_SELECTABLE_REJECT': 0x805A0A70 - SEL[1],
    'SEL_R25_CLAMP': 0x805AB358 - SEL[1],
    'SEL_COUNT': 0x805AB42C - SEL[1],
    'SEL_LIST': 0x805AB704 - SEL[1],
    'SEL_XPOS': 0x805AB728 - SEL[1],
    'SEL_SPRITE': 0x805AB8C4 - SEL[1],
    'SEL_SIZE': 0x805AB918 - SEL[1],
    'SEL_NAME_E3_0': 0x805C1944 - SEL[5],
    'M1_CUP_SPRITES': 0x80322FD0 - M1[4],     # 11 x u32 cup -> icon sprite
    'SEL_CUP_SPRITES': 0x805BDFF0 - SEL[4],    # same table in fze.sel.rel
    'WIN_CUP_NAMES': 0x1C80,                   # fze.winning.rel section 5: [language][6] name pointers
}
# Original instructions at the hook sites (checked before patching a DOL/REL).
DOL_HOOKS = {
    0x8000E320: (0x4BFFFD11, 'hook_link'),     # bl Link (OSLink)
    0x8000E35C: (0x4BFFFCD5, 'hook_link'),     # bl Link (OSLinkFixed)
}
# OSInit: "lis r3, 0x801b; addi r3, r3, 0x7930" (__ArenaLo) -> BASE + SIZE
_lo = BASE + SIZE
ARENA_LO = {
    0x8000A4F8: (0x3C60801B, 0x3C600000 | (((_lo + 0x8000) >> 16) & 0xFFFF)),
    0x8000A4FC: (0x38637930, 0x38630000 | (_lo & 0xFFFF)),
}


def build():
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'cup_patch.s')
    asm = Assembler(BASE, SYMBOLS)
    blob = asm.assemble(open(path).read())
    return blob, asm.symbols


def bl(src, dst):
    off = dst - src
    assert -0x2000000 <= off < 0x2000000
    return 0x48000001 | (off & 0x3FFFFFC)


def patch_dol(dol, blob, sym, cups):
    dol = bytearray(dol)
    offs = list(struct.unpack('>18I', dol[0:72]))
    addrs = list(struct.unpack('>18I', dol[72:144]))
    sizes = list(struct.unpack('>18I', dol[144:216]))

    def file_off(addr):
        for i in range(18):
            if sizes[i] and addrs[i] <= addr < addrs[i] + sizes[i]:
                return offs[i] + addr - addrs[i]
        raise ValueError(hex(addr))

    for addr, (orig, target) in DOL_HOOKS.items():
        o = file_off(addr)
        cur = struct.unpack('>I', dol[o:o + 4])[0]
        if cur != orig:
            raise SystemExit(f'unexpected instruction {cur:08x} at {addr:#x} (not GFZE01 or already patched)')
        dol[o:o + 4] = struct.pack('>I', bl(addr, sym[target]))
    for addr, (orig, new) in ARENA_LO.items():
        o = file_off(addr)
        cur = struct.unpack('>I', dol[o:o + 4])[0]
        if cur != orig:
            raise SystemExit(f'unexpected instruction {cur:08x} at {addr:#x}')
        dol[o:o + 4] = struct.pack('>I', new)
    assert len(blob) <= SIZE, 'patch larger than the reserved space'
    blob = bytearray(blob)
    cfg = sym['config'] - BASE
    blob[cfg] = len(cups)
    for i, (name, courses, sprite) in enumerate(cups):
        row = (list(courses) + [-1] * 6)[:6]
        o = sym['cfg_rows'] - BASE + 12 * i
        blob[o:o + 12] = struct.pack('>6h', *row)
        o = sym['cfg_sprites'] - BASE + 4 * i
        blob[o:o + 4] = struct.pack('>I', sprite)
        for key, text in (('cfg_names', name), ('cfg_names_uc', name.upper())):
            o = sym[key] - BASE + 32 * i
            n = text.encode('latin1')[:31]
            blob[o:o + 32] = n + bytes(32 - len(n))
    slot = next(i for i in range(7) if sizes[i] == 0)
    start = (len(dol) + 31) & ~31
    dol += bytes(start - len(dol)) + blob + bytes((-len(blob)) % 32)
    offs[slot], addrs[slot], sizes[slot] = start, BASE, (len(blob) + 31) & ~31
    dol[0:216] = struct.pack('>18I', *offs) + struct.pack('>18I', *addrs) + struct.pack('>18I', *sizes) \
        + dol[216:216]
    return bytes(dol)


def header(blob, sym):
    lines = ['// Generated by tools/build_cup_patch.py from tools/cup_patch.s. Do not edit.',
             '#pragma once', '#include <cstdint>', '', 'namespace fzgx::cup_patch', '{',
             f'constexpr std::uint32_t kBase = {BASE:#010x};']
    names = ['config', 'cfg_count', 'cfg_rows', 'cfg_sprites', 'cfg_arrows', 'cfg_names', 'cfg_names_uc',
             'hook_link', 'v_links', 'v_page']
    for n in names:
        camel = 'k' + ''.join(p.capitalize() for p in n.split('_'))
        lines.append(f'constexpr std::uint32_t {camel} = {sym[n]:#010x};')
    lines.append('struct DolHook { std::uint32_t addr, original, target; };')
    lines.append('constexpr DolHook kDolHooks[] = {')
    for addr, (orig, target) in DOL_HOOKS.items():
        lines.append(f'    {{{addr:#010x}, {orig:#010x}, {sym[target]:#010x}}},')
    lines.append('};')
    lines.append('struct DolWord { std::uint32_t addr, original, replacement; };')
    lines.append('constexpr DolWord kArenaLo[] = {')
    for addr, (orig, new) in ARENA_LO.items():
        lines.append(f'    {{{addr:#010x}, {orig:#010x}, {new:#010x}}},')
    lines.append('};')
    lines.append(f'constexpr std::uint32_t kReserved = {SIZE:#x};')
    lines.append(f'constexpr std::uint8_t kBlob[{len(blob)}] = {{')
    for i in range(0, len(blob), 16):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in blob[i:i + 16]) + ',')
    lines.append('};')
    lines.append('}  // namespace fzgx::cup_patch')
    return '\n'.join(lines) + '\n'


def parse_cups(text):
    cups = []
    for part in filter(None, text.split(';')):
        name, courses, sprite = part.split(':')
        cups.append((name, [int(c) for c in courses.split(',')], int(sprite, 0)))
    return cups


if __name__ == '__main__':
    blob, sym = build()
    if sys.argv[1] == 'header':
        out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'cup_patch_blob.hpp')
        open(out, 'w').write(header(blob, sym))
        print(f'{len(blob)} bytes -> {out}')
    elif sys.argv[1] == 'dol':
        cups = parse_cups(sys.argv[4]) if len(sys.argv) > 4 else [('Editor Cup', [7, 13, 21, 25, 27], 0xA102)]
        open(sys.argv[3], 'wb').write(patch_dol(open(sys.argv[2], 'rb').read(), blob, sym, cups))
        print(f'patched {sys.argv[3]}: {len(blob)} bytes at {BASE:#x}, links counter at {sym["v_links"]:#x}')
    elif sys.argv[1] == 'syms':
        for k, v in sorted(sym.items(), key=lambda kv: kv[1]):
            print(f'{v:#010x} {k}')
